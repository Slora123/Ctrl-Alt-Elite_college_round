"""Mounts the Paper Environment API inside this app (same process, same login).

paper_env is imported lazily and optionally: if the package is not installed the rest of CrisisGrid still works and
``/paper-env`` simply is not there (the health endpoint says so).
"""
from __future__ import annotations

import logging
from pathlib import Path
from typing import Any

from fastapi import FastAPI

from .config import Settings
from .container import AppContainer

log = logging.getLogger("crisisgrid.paper_env")


def mount_paper_env(app: FastAPI, container: AppContainer, settings: Settings) -> Any | None:
    """Returns the paper_env ``App`` (to start/stop with this app's lifespan), or None when it is not mounted."""
    if not settings.paper_env_enabled:
        return None
    try:
        from paper_env.api import create_api
        from paper_env.auth import Principal
        from paper_env.config import Settings as PESettings
        from paper_env.container import build_app
    except ImportError as e:  # pragma: no cover - depends on the install
        log.warning("paper_env is not installed; /paper-env is disabled (%s)", e)
        return None

    class JwtAuthenticator:
        """Same users, same tokens: session JWTs and API tokens verified by the CrisisGrid auth service."""

        def authenticate(self, token: str) -> Principal | None:
            user = container.auth.authenticate(token)
            return Principal(user.id, user.name, user.role) if user else None

    pe_settings = PESettings(data_dir=Path(settings.paper_env_dir).resolve(), enable_terminal=settings.paper_env_enable_terminal,
                             require_auth=settings.auth_enabled)
    core = build_app(pe_settings, authenticator=JwtAuthenticator() if settings.auth_enabled else None)
    app.mount("/paper-env", create_api(core, manage_lifecycle=False))
    _bridge_notebooks(core, container)
    return core


def _bridge_notebooks(core: Any, container: AppContainer) -> None:
    """Generated notebooks become editable notebooks: one paper environment per paper ('paper-<id>', the same one the
    website's "Open notebook" opens), owned by the paper's owner. On approval the pipeline runs what is in it now."""
    if container.orchestrator is None:
        return
    from paper_env.domain import Author, EnvSpec
    from paper_env.repos import NotFound

    def alias(paper_id: str) -> str:
        return "paper-" + paper_id[-8:]

    def sink(paper_id: str, cells: list[dict[str, str]], requirements: list[str]) -> str | None:
        paper = container.papers.get(paper_id)
        try:
            env = core.paper_envs.get_by_alias(alias(paper_id))
        except NotFound:
            env = core.paper_envs.create(alias(paper_id), paper.paper_hash if paper else paper_id,
                                         EnvSpec(requirements=list(requirements)), owner_id=paper.owner_id if paper else None)
        for old in core.notebook.list_cells(env.id):  # a regeneration replaces the previous draft
            if old.status.value != "running":
                core.notebook.delete_cell(old.id)
        core.notebook.add_cell(env.id, "## Generated by CrisisGrid\n\nWritten from the paper's stated setup, not the authors' code. "
                               "Review and edit freely; approving the gate runs exactly the code cells below.",
                               Author.GENERATOR, cell_type="markdown")
        for c in cells:
            core.notebook.add_cell(env.id, c["source"], Author.GENERATOR)
        spec = core.paper_envs.get_spec(env.id)
        if requirements and sorted(spec.requirements) != sorted(requirements):
            spec.requirements = list(requirements)
            with core.uow() as u:
                u.paper_envs.update_spec(spec)
        return str(env.id)

    def source(env_id: str) -> list[dict[str, str]] | None:
        try:
            return [{"kind": "code", "source": core.notebook.source_of(c.id)} for c in core.notebook.list_cells(env_id)
                    if c.cell_type == "code"]
        except NotFound:
            return None

    container.orchestrator.d.notebook_sink = sink
    container.orchestrator.d.notebook_source = source
