"""Persistence interfaces. Services depend on these, never on SQLAlchemy.

All methods accept and return plain domain objects. A ``UnitOfWork`` groups
repos on one transaction so multi-step operations (e.g. ``apply_edit``) are atomic.
"""
from __future__ import annotations

from typing import Callable, Protocol, Sequence

from ..domain import (
    BlockedAction,
    Cell,
    CellRun,
    CellVersion,
    Checkpoint,
    EnvSpec,
    Event,
    EventType,
    DatasetManifest,
    PaperEnv,
    Run,
)


class NotFound(LookupError):
    pass


class Conflict(ValueError):
    """Uniqueness violation (e.g. duplicate alias)."""


class PaperEnvRepo(Protocol):
    def add(self, env: PaperEnv, spec: EnvSpec) -> None: ...
    def get(self, paper_env_id: str) -> PaperEnv: ...
    def get_by_alias(self, alias: str) -> PaperEnv: ...
    def list(self) -> list[PaperEnv]: ...
    def update(self, env: PaperEnv) -> None: ...
    def delete(self, paper_env_id: str) -> None: ...
    def get_spec(self, spec_id: str) -> EnvSpec: ...
    def update_spec(self, spec: EnvSpec) -> None: ...


class CellRepo(Protocol):
    def add_cell(self, cell: Cell) -> None: ...
    def get_cell(self, cell_id: str) -> Cell: ...
    def list_cells(self, paper_env_id: str) -> list[Cell]: ...  # ordered by position
    def update_cell(self, cell: Cell) -> None: ...
    def delete_cell(self, cell_id: str) -> None: ...
    def add_version(self, version: CellVersion) -> None: ...
    def get_version(self, version_id: str) -> CellVersion: ...
    def list_versions(self, cell_id: str) -> list[CellVersion]: ...  # oldest first


class RunRepo(Protocol):
    def add_run(self, run: Run) -> None: ...
    def get_run(self, run_id: str) -> Run: ...
    def update_run(self, run: Run) -> None: ...
    def list_runs(self, paper_env_id: str) -> list[Run]: ...
    def add_cell_run(self, cell_run: CellRun) -> None: ...
    def update_cell_run(self, cell_run: CellRun) -> None: ...
    def list_cell_runs(self, run_id: str) -> list[CellRun]: ...


class DatasetRepo(Protocol):
    def upsert(self, manifest: DatasetManifest) -> None: ...
    def get(self, dataset_id: str) -> DatasetManifest: ...
    def exists(self, dataset_id: str) -> bool: ...
    def list(self) -> list[DatasetManifest]: ...
    def delete(self, dataset_id: str) -> None: ...
    # usage tracking so LRU eviction never removes a dataset used by an active run
    def mark_in_use(self, run_id: str, dataset_id: str) -> None: ...
    def release_run(self, run_id: str) -> None: ...
    def in_use_dataset_ids(self) -> set[str]: ...


class EventStore(Protocol):
    def append(self, event: Event) -> Event: ...  # assigns a monotonically increasing seq
    def list(
        self,
        after_seq: int = 0,
        limit: int = 1000,
        run_id: str | None = None,
        paper_env_id: str | None = None,
        types: Sequence[EventType] | None = None,
    ) -> list[Event]: ...


class CheckpointRepo(Protocol):
    def add(self, checkpoint: Checkpoint) -> None: ...
    def get(self, checkpoint_id: str) -> Checkpoint: ...
    def list(self, paper_env_id: str, run_id: str | None = None) -> list[Checkpoint]: ...


class BlockedActionRepo(Protocol):
    def add(self, action: BlockedAction) -> None: ...
    def get(self, action_id: str) -> BlockedAction: ...
    def update(self, action: BlockedAction) -> None: ...
    def list_pending(self, paper_env_id: str | None = None) -> list[BlockedAction]: ...


class UnitOfWork(Protocol):
    paper_envs: PaperEnvRepo
    cells: CellRepo
    runs: RunRepo
    datasets: DatasetRepo
    events: EventStore
    checkpoints: CheckpointRepo
    blocked: BlockedActionRepo

    def __enter__(self) -> "UnitOfWork": ...
    def __exit__(self, exc_type, exc, tb) -> None: ...  # commit on success, rollback on error


UnitOfWorkFactory = Callable[[], UnitOfWork]
